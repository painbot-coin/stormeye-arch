/** Fallback avatar when no URL set – randomuser.me, globally accessible */
function avatarUrl(name) {
  const h = name.split('').reduce((a, c) => ((a << 5) - a) + c.charCodeAt(0), 0)
  const id = (Math.abs(h) % 99) || 1
  const female = /^(Dorothy|Carol)\s/i.test(name)
  const g = female ? 'women' : 'men'
  return `https://randomuser.me/api/portraits/med/${g}/${id}.jpg`
}

